nb = nbformat.read(NB_PATH, as_version=4)
replaced = []
for cell in nb.cells:
    if cell.cell_type == "markdown":
        key = cell.source.strip()
        if key in TEXTS:
            cell.source = TEXTS[key]
            replaced.append(key)

missing = set(TEXTS) - set(replaced)
assert not missing, f"не найдены плейсхолдеры: {missing}"
nbformat.write(nb, NB_PATH)
nbformat.validate(nb)
print(f"заменено ячеек: {len(replaced)}")
